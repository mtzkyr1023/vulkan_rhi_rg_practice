		// Atlas: 16 columns x 6 rows of 8x8 cells. The 96th slot (bottom right) is
		// solid white; rectangles sample it, so glyphs and fills share one draw.
		constexpr u32 kAtlasColumns = 16;
		constexpr u32 kAtlasRows = 6;
		constexpr u32 kAtlasWidth = kAtlasColumns * 8;
		constexpr u32 kAtlasHeight = kAtlasRows * 8;
		constexpr u32 kWhiteSlot = 95;

		// Must match HudConstants in hud.hlsl.
		struct HudGpuConstants
		{
			f32 screenSize[2]{};
			f32 pad[2]{};
		};
