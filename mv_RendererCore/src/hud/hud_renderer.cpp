	bool HudRenderer::initialize(
		const std::shared_ptr<rhi::IRHI>& rhi,
		const Shaders& shaders,
		rhi::ETextureFormat colorFormat,
		u32 framesInFlight)
	{
		if (!rhi || shaders.vs == nullptr || shaders.ps == nullptr || framesInFlight == 0)
			return false;

		rhi_ = rhi;

		// The atlas, baked from the bit patterns: white where a bit is set, alpha 0
		// elsewhere -- RGB stays white so linear filtering never darkens an edge.
		{
			std::vector<u32> pixels((size_t)kAtlasWidth * kAtlasHeight, 0x00FFFFFFu);

			for (u32 slot = 0; slot < 96; slot++)
			{
				const u32 cellX = (slot % kAtlasColumns) * 8;
				const u32 cellY = (slot / kAtlasColumns) * 8;

				for (u32 row = 0; row < 8; row++)
				{
					const unsigned char bits = slot == kWhiteSlot ? 0xFF : kFont[slot < 95 ? slot : 0][row];

					for (u32 column = 0; column < 8; column++)
					{
						if (bits & (1u << column))
							pixels[(size_t)(cellY + row) * kAtlasWidth + cellX + column] = 0xFFFFFFFFu;
					}
				}
			}

			rhi::TextureDesc desc{};
			desc.width = kAtlasWidth;
			desc.height = kAtlasHeight;
			desc.depth = 1;
			desc.usage = rhi::ETextureUsage::eSampled | rhi::ETextureUsage::eTransferDst;
			desc.format = rhi::ETextureFormat::eR8G8B8A8_UNORM;
			desc.memoryType = rhi::EMemoryType::eDeviceLocalImage;

			fontTexture_ = rhi_->createTexture(desc);

			const rhi::TextureUpload upload{ pixels.data(), (u64)kAtlasWidth * kAtlasHeight * 4 };
			rhi_->uploadTexture(fontTexture_, &upload, 1);
		}

		{
			rhi::BindGroupLayoutDesc groupLayoutDesc{};
			groupLayoutDesc.bindings.push_back({
				.binding = 0, .count = 1,
				.type = rhi::EDescriptorType::eSampledImage, .stages = rhi::EShaderStage::eFragment });
			groupLayoutDesc.bindings.push_back({
				.binding = 1, .count = 1,
				.type = rhi::EDescriptorType::eSampler, .stages = rhi::EShaderStage::eFragment });

			bindGroupLayout_ = rhi_->createBindGroupLayout(groupLayoutDesc);

			rhi::BindGroupDesc groupDesc{};
			groupDesc.layout = bindGroupLayout_;
			groupDesc.sampledTextures.push_back({ .binding = 0, .texture = fontTexture_ });
			groupDesc.samplers.push_back({ .binding = 1,
				.sampler = { .filter = rhi::EFilterMode::eLinear, .address = rhi::EAddressMode::eClampToEdge } });

			bindGroup_ = rhi_->createBindGroup(groupDesc);

			rhi::PipelineLayoutDesc layoutDesc{};
			layoutDesc.bindGroups.push_back(bindGroupLayout_);
			layoutDesc.pushConstantSize = sizeof(HudGpuConstants);

			pipelineLayout_ = rhi_->createPipelineLayout(layoutDesc);
		}

		rhi::ShaderDesc vsDesc{ rhi::EShaderType::eVertex, shaders.vs, shaders.vsSize, "VSMain" };
		rhi::ShaderDesc psDesc{ rhi::EShaderType::eFragment, shaders.ps, shaders.psSize, "PSMain" };

		rhi::GraphicsPipelineDesc pipelineDesc{};
		pipelineDesc.vs = rhi_->createShader(vsDesc);
		pipelineDesc.ps = rhi_->createShader(psDesc);
		pipelineDesc.layoutHandle = pipelineLayout_;

		pipelineDesc.vertexLayout.bindings.push_back({
			.binding = 0, .stride = sizeof(Vertex), .perInstance = false });
		pipelineDesc.vertexLayout.attributes.push_back({
			.location = 0, .semanticName = "POSITION", .semanticIndex = 0,
			.binding = 0, .format = rhi::EVertexFormat::eFloat2, .offset = (u32)offsetof(Vertex, position) });
		pipelineDesc.vertexLayout.attributes.push_back({
			.location = 1, .semanticName = "TEXCOORD", .semanticIndex = 0,
			.binding = 0, .format = rhi::EVertexFormat::eFloat2, .offset = (u32)offsetof(Vertex, uv) });
		pipelineDesc.vertexLayout.attributes.push_back({
			.location = 2, .semanticName = "COLOR", .semanticIndex = 0,
			.binding = 0, .format = rhi::EVertexFormat::eR8G8B8A8_UNORM, .offset = (u32)offsetof(Vertex, color) });

		// Over the finished image: no depth at all, straight alpha.
		pipelineDesc.depth.depthTestEnable = false;
		pipelineDesc.depth.depthWriteEnable = false;

		pipelineDesc.rasterizer.cullMode = rhi::ECullMode::eNone;

		pipelineDesc.blend.blendEnable = true;
		pipelineDesc.blend.srcColorFactor = rhi::EBlendFactor::eSrcAlpha;
		pipelineDesc.blend.dstColorFactor = rhi::EBlendFactor::eOneMinusSrcAlpha;
		pipelineDesc.blend.colorOp = rhi::EBlendOp::eAdd;
		pipelineDesc.blend.srcAlphaFactor = rhi::EBlendFactor::eOne;
		pipelineDesc.blend.dstAlphaFactor = rhi::EBlendFactor::eOneMinusSrcAlpha;
		pipelineDesc.blend.alphaOp = rhi::EBlendOp::eAdd;

		pipelineDesc.colorFormats = { colorFormat };
		pipelineDesc.depthFormat = rhi::ETextureFormat::eUndefined;

		pipeline_ = rhi_->createGraphicsPipeline(pipelineDesc);

		if (pipeline_ == INVALID_HANDLE)
			return false;

		buffers_.resize(framesInFlight, INVALID_HANDLE);
		counts_.resize(framesInFlight, 0);

		for (u32 i = 0; i < framesInFlight; i++)
		{
			rhi::BufferDesc desc{};
			desc.size = (u64)kMaxVertices * sizeof(Vertex);
			desc.usage = rhi::EBufferUsage::eVertex;
			desc.memoryType = rhi::EMemoryType::eHostVisibleBuffer;

			buffers_[i] = rhi_->createBuffer(desc);

			if (buffers_[i] == INVALID_HANDLE)
				return false;
		}

		queue_.reserve(kMaxVertices);

		ready_ = true;

		return true;
	}

	void HudRenderer::deinitialize()
	{
		if (rhi_)
		{
			for (rhi::BufferHandle buffer : buffers_)
			{
				if (buffer != INVALID_HANDLE)
					rhi_->releaseBuffer(buffer);
			}

			if (fontTexture_ != INVALID_HANDLE)
				rhi_->freeImage(fontTexture_);
		}

		buffers_.clear();
		counts_.clear();
		queue_.clear();

		fontTexture_ = INVALID_HANDLE;
		ready_ = false;
		rhi_.reset();
	}

	void HudRenderer::begin(u32 width, u32 height)
	{
		queue_.clear();

		width_ = (f32)(std::max)(width, 1u);
		height_ = (f32)(std::max)(height, 1u);
	}

	void HudRenderer::quad(f32 x, f32 y, f32 w, f32 h, f32 u0, f32 v0, f32 u1, f32 v1, u32 color)
	{
		if (queue_.size() + 6 > kMaxVertices)
			return;

		const Vertex topLeft{ { x, y }, { u0, v0 }, color };
		const Vertex topRight{ { x + w, y }, { u1, v0 }, color };
		const Vertex bottomLeft{ { x, y + h }, { u0, v1 }, color };
		const Vertex bottomRight{ { x + w, y + h }, { u1, v1 }, color };

		queue_.push_back(topLeft);
		queue_.push_back(topRight);
		queue_.push_back(bottomRight);
		queue_.push_back(topLeft);
		queue_.push_back(bottomRight);
		queue_.push_back(bottomLeft);
	}

	void HudRenderer::rect(f32 x, f32 y, f32 w, f32 h, u32 color)
	{
		// The middle of the white slot, clear of any filtered neighbour.
		const f32 u = ((f32)(kWhiteSlot % kAtlasColumns) * 8.0f + 4.0f) / (f32)kAtlasWidth;
		const f32 v = ((f32)(kWhiteSlot / kAtlasColumns) * 8.0f + 4.0f) / (f32)kAtlasHeight;

		quad(x, y, w, h, u, v, u, v, color);
	}

	void HudRenderer::text(f32 x, f32 y, f32 scale, u32 color, const char* string)
	{
		if (string == nullptr)
			return;

		f32 penX = x;

		for (const char* c = string; *c != '\0'; c++)
		{
			const u32 code = (u32)(unsigned char)*c;

			if (code >= 0x20 && code < 0x7F && code != 0x20)
			{
				const u32 slot = code - 0x20;
				const f32 u0 = (f32)((slot % kAtlasColumns) * 8) / (f32)kAtlasWidth;
				const f32 v0 = (f32)((slot / kAtlasColumns) * 8) / (f32)kAtlasHeight;
				const f32 u1 = u0 + 8.0f / (f32)kAtlasWidth;
				const f32 v1 = v0 + 8.0f / (f32)kAtlasHeight;

				quad(penX, y, kGlyphSize * scale, kGlyphSize * scale, u0, v0, u1, v1, color);
			}

			penX += kGlyphSize * scale;
		}
	}

	f32 HudRenderer::textWidth(f32 scale, const char* string)
	{
		return string ? (f32)std::strlen(string) * kGlyphSize * scale : 0.0f;
	}

	void HudRenderer::end(u32 frameIndex)
	{
		if (!ready_ || frameIndex >= buffers_.size())
			return;

		counts_[frameIndex] = (u32)queue_.size();

		if (!queue_.empty())
			rhi_->writeBuffer(buffers_[frameIndex], queue_.data(), queue_.size() * sizeof(Vertex), 0);
	}

	void HudRenderer::record(rhi::CommandBufferHandle cmd, u32 frameIndex)
	{
		if (!ready_ || frameIndex >= buffers_.size() || counts_[frameIndex] == 0)
			return;

		rhi_->bindGraphicsPipeline(cmd, pipeline_);
		rhi_->bindBindGroup(cmd, pipelineLayout_, 0, bindGroup_);

		HudGpuConstants constants{};
		constants.screenSize[0] = width_;
		constants.screenSize[1] = height_;

		rhi_->pushConstants(cmd, pipelineLayout_, &constants, sizeof(constants), 0);

		rhi_->bindVertexBuffer(cmd, 0, buffers_[frameIndex], sizeof(Vertex), 0);
		rhi_->draw(cmd, counts_[frameIndex], 1, 0, 0);
	}
